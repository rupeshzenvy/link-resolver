(() => {
  const CONTINUE_RE = new RegExp("^\\s*(get\\s*link|get\\s*the\\s*link|continue|skip(\\s*ad)?|proceed|go\\s*to\\s*link|open\\s*link|click\\s*here(\\s*to\\s*continue)?|next|i('|’)?m\\s*not\\s*a\\s*robot|verify|unlock|visit\\s*link|download|go\\s*to\\s*destination|get\\s*download\\s*link)\\b", 'i');
  const PARAM_KEYS = ["url","u","link","target","dest","destination","redirect","redirect_url","r","to","go","out","q","href","l","k","id","token","api"];
  const SPEEDUP = 20;

  // Countdown timers run SPEEDUP times faster.
  const st = window.setTimeout, si = window.setInterval;
  window.setTimeout = (f, d, ...a) => st(f, Math.max(0, (d || 0) / SPEEDUP), ...a);
  window.setInterval = (f, d, ...a) => si(f, Math.max(10, (d || 0) / SPEEDUP), ...a);

  // Popups and popunders are blocked; the last one is offered in the badge in
  // case a site opens the real destination in a new tab.
  let lastPopup = null;
  window.open = (u) => { if (u) { lastPopup = new URL(u, location.href).href; render(); } return null; };

  const looksLikeUrl = s => {
    if (!/^https?:\/\/[^\s"'<>]+$/i.test(s)) return false;
    try { return !!new URL(s).hostname; } catch { return false; }
  };
  const decodings = v => {
    const out = [];
    for (let i = 0; i < 3; i++) { try { const d = decodeURIComponent(v); if (d === v) break; v = d; } catch { break; } }
    out.push(v);
    for (const c of [v, [...v].reverse().join('')]) {
      if (!/^[A-Za-z0-9+/_-]{16,}={0,2}$/.test(c)) continue;
      try { const b = atob(c.replace(/-/g, '+').replace(/_/g, '/')); out.push(b); out.push(decodeURIComponent(b)); } catch {}
    }
    return out;
  };
  // Destination URL hidden in this page's query string / hash.
  const embeddedUrl = () => {
    const params = [...new URLSearchParams(location.search)];
    if (location.hash.length > 1) params.push(...new URLSearchParams(location.hash.slice(1)), ['#', location.hash.slice(1)]);
    const rank = k => { const i = PARAM_KEYS.indexOf(k.toLowerCase()); return i < 0 ? 99 : i; };
    params.sort(([a], [b]) => rank(a) - rank(b));
    for (const [, v] of params) {
      for (const d of decodings(v)) {
        if (looksLikeUrl(d.trim()) && new URL(d.trim()).hostname !== location.hostname) return d.trim();
      }
    }
    return null;
  };

  const jump = embeddedUrl();
  if (jump) { location.replace(jump); return; }

  let status = 'Waiting…', badge = null;
  function render() {
    if (!document.body) return;
    if (!badge) {
      badge = document.createElement('div');
      badge.style.cssText = 'position:fixed;left:12px;right:12px;bottom:12px;z-index:2147483647;padding:10px 14px;' +
        'border-radius:12px;background:rgba(20,20,22,.92);color:#fff;font:14px/1.35 -apple-system,system-ui,sans-serif;' +
        'box-shadow:0 4px 18px rgba(0,0,0,.35);pointer-events:auto';
      document.body.appendChild(badge);
    }
    badge.textContent = '';
    const line = document.createElement('div');
    line.textContent = 'Link Resolver: ' + status;
    badge.appendChild(line);
    if (lastPopup) {
      const a = document.createElement('a');
      a.href = lastPopup; a.textContent = 'Blocked popup: ' + lastPopup;
      a.style.cssText = 'display:block;margin-top:4px;color:#8ab4ff;word-break:break-all;font-size:12px';
      badge.appendChild(a);
    }
  }

  const visible = el => {
    const r = el.getBoundingClientRect(), s = getComputedStyle(el);
    return r.width > 4 && r.height > 4 && s.visibility !== 'hidden' && s.display !== 'none' && +s.opacity > 0.1;
  };
  const clickedAt = new WeakMap();

  function tick() {
    render();
    if (document.querySelector('iframe[src*="recaptcha"], iframe[src*="hcaptcha"], iframe[src*="turnstile"], .g-recaptcha, .h-captcha, .cf-turnstile')) {
      status = 'solve the CAPTCHA, then I\'ll continue';
    }
    const els = document.querySelectorAll('a, button, input[type=submit], input[type=button], [role=button], div[onclick], span[onclick]');
    for (const el of els) {
      if (badge && badge.contains(el)) continue;
      const t = (el.innerText || el.value || el.getAttribute('aria-label') || '').trim();
      if (t.length >= 60 || !CONTINUE_RE.test(t) || el.disabled || el.classList.contains('disabled') || !visible(el)) continue;
      if (Date.now() - (clickedAt.get(el) || 0) < 4000) continue;
      clickedAt.set(el, Date.now());
      status = `clicked "${t}"`;
      render();
      el.click();
      return;
    }
  }
  si(tick, 700); // the page's own, un-sped-up interval
})();
